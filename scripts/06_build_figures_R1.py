# Figure 4: Domain-level Cox HRs (lollipop chart)
# ═══════════════════════════════════════════════════════════════════════
print("\nFigure 4 — Domain-level lollipop chart")
D = pd.read_csv(os.path.join(TAB, "cox_R1_domain.csv"))
DOMAIN_LABEL_FULL = {"SCAU_GI": "Gastrointestinal",
                     "SCAU_URI": "Urinary",
                     "SCAU_CV": "Cardiovascular",
                     "SCAU_THERM": "Thermoregulatory",
                     "SCAU_PUPIL": "Pupillomotor (SCAU22)",
                     "SCAU_SEX": "Sexual (SCAU23–25)",
                     "SCAU_TOTAL": "SCOPA-AUT total"}
D["Label"] = D.Domain.map(DOMAIN_LABEL_FULL)
D = D.sort_values("HR").reset_index(drop=True)
# Significance + direction → colour
def dom_color(row):
    if row.p < 0.05 and row.HR > 1: return "#4878D0"   # blue: significant positive
    if row.p < 0.05 and row.HR < 1: return "#956CB4"   # purple: significant inverse
    return "#A0A0A0"                                    # grey: NS
D["color"] = D.apply(dom_color, axis=1)

# Determine x-axis range based on actual CI bounds, with margin for p-value column
ci_max = D.CI_high.max()
ci_min = D.CI_low.min()
XLIM_LO = min(0.85, ci_min - 0.05)
PVAL_X = max(ci_max + 0.06, 1.40)        # x-position for p-value annotations
XLIM_HI = PVAL_X + 0.18

fig, ax = plt.subplots(figsize=(6.0, 3.7), constrained_layout=True)
y = np.arange(len(D))
# Forest-plot style: ONLY the 95% CI line + point estimate marker.
# No lollipop stick — that was being misread as a second CI.
for yi, (_, r) in zip(y, D.iterrows()):
    ax.plot([r.CI_low, r.CI_high], [yi, yi],
            color=r["color"], linewidth=1.6, solid_capstyle="butt", zorder=2)
    # Caps at CI ends
    for x_cap in (r.CI_low, r.CI_high):
        ax.plot([x_cap, x_cap], [yi-0.18, yi+0.18],
                color=r["color"], linewidth=1.0, zorder=2)
    # Point estimate marker
    sig = r.p < 0.05
    if sig:
        ax.scatter(r.HR, yi, color=r["color"], s=70,
                   edgecolor="black", linewidth=0.6, zorder=3)
    else:
        ax.scatter(r.HR, yi, facecolor="white", s=42,
                   edgecolor=r["color"], linewidth=1.0, zorder=3)

ax.axvline(1, color="grey", linestyle="--", linewidth=0.7, zorder=1)
ax.set_yticks(y); ax.set_yticklabels(D.Label, fontsize=9)
ax.set_xlabel("Adjusted hazard ratio (95% CI, Model B)")
ax.set_xlim(XLIM_LO, XLIM_HI)

# p-values in a clear right-hand column (anchored, not crashing into CIs)
for yi, (_, r) in zip(y, D.iterrows()):
    p_str = "p < 0.001" if r.p < 0.001 else f"p = {r.p:.3f}"
    ax.text(PVAL_X, yi, p_str, ha="left", va="center",
            fontsize=7.5, color="black", family="monospace")

# Footer note on marker convention
ax.text(0.99, -0.18,
        "● filled = FDR-significant   ○ hollow = NS",
        transform=ax.transAxes, ha="right", va="top",
        fontsize=7, color="#444444")
save(fig, "Figure4_domain_lollipop_R1")

# ═══════════════════════════════════════════════════════════════════════
# Figure 5: Per-milestone HR heatmap (items × outcomes) with FDR stars
# ═══════════════════════════════════════════════════════════════════════
print("\nFigure 5 — Per-milestone heatmap")
HR_wide = pd.read_csv(os.path.join(TAB, "cox_R1_heatmap_HR.csv"), index_col=0)
P_wide  = pd.read_csv(os.path.join(TAB, "cox_R1_heatmap_p_fdr.csv"), index_col=0)
keep_items = [f"SCAU{i}" for i in range(1, 22)]
HR_wide = HR_wide.loc[HR_wide.index.intersection(keep_items)]
P_wide  = P_wide.loc[HR_wide.index]
out_order = ["m10", "m11", "m12", "m13", "m14", "m15",
             "pure_cognitive", "pure_neuropsych"]
HR_wide = HR_wide[[c for c in out_order if c in HR_wide.columns]]
P_wide  = P_wide [[c for c in out_order if c in P_wide.columns]]
HR_wide = HR_wide.reindex(sorted(HR_wide.index, key=lambda i: int(i.replace("SCAU",""))))
P_wide = P_wide.reindex(HR_wide.index)

label_col = {"m10": "m10 (MoCA<21)", "m11": "m11 (UPDRS-I cog)",
             "m12": "m12 (Halluc.)", "m13": "m13 (Apathy)",
             "m14": "m14 (Inv. dem.)", "m15": "m15 (MDS-PDD)",
             "pure_cognitive": "Pure cog (m10+14+15)",
             "pure_neuropsych": "Pure NP (m12+13)"}
cmap = LinearSegmentedColormap.from_list("hot_cool",
    ["#3B5998", "#FFFFFF", "#B22222"], N=256)
# Failed Cox estimates have HR near 0 or massive — flag and treat as missing
# for the color scale. Threshold: HR outside [0.1, 10] is considered unreliable.
HR_vals = HR_wide.values.astype(float).copy()
HR_for_color = HR_vals.copy()
failed_mask = (HR_vals < 0.1) | (HR_vals > 10)
HR_for_color[failed_mask] = np.nan
log_HR = np.log2(HR_for_color)
# Cap color scale at ±1.5 (HR 0.35 to 2.83) — values beyond this are saturated.
VMAX = 1.5

fig, ax = plt.subplots(figsize=(6.0, 6.0), constrained_layout=True)
# Use masked array so NaN cells render as the masked color (light grey)
log_HR_masked = np.ma.array(log_HR, mask=np.isnan(log_HR))
cmap.set_bad(color="#E8E8E8")
im = ax.imshow(log_HR_masked, cmap=cmap, vmin=-VMAX, vmax=VMAX, aspect="auto")
ax.set_xticks(np.arange(HR_wide.shape[1]))
ax.set_xticklabels([label_col.get(c, c) for c in HR_wide.columns],
                    rotation=45, ha="right", fontsize=7.5)
ax.set_yticks(np.arange(HR_wide.shape[0]))
ax.set_yticklabels([ITEM_LABELS[i] for i in HR_wide.index], fontsize=8)
# Annotate cells: HR value and FDR star (or "—" for failed/NaN)
for i, item in enumerate(HR_wide.index):
    for j, out in enumerate(HR_wide.columns):
        hr = HR_vals[i, j]
        pv = P_wide.iloc[i, j]
        failed = failed_mask[i, j]
        if np.isnan(hr) or failed:
            txt = "—"; c = "#888888"
        else:
            star = ""
            if pd.notna(pv):
                if pv < 0.001: star = "***"
                elif pv < 0.01: star = "**"
                elif pv < 0.05: star = "*"
            txt = f"{hr:.2f}{star}"
            # Text contrast against actual color cell
            cell_log = max(-VMAX, min(VMAX, np.log2(hr)))
            c = "white" if abs(cell_log) > VMAX * 0.6 else "black"
        ax.text(j, i, txt, ha="center", va="center",
                fontsize=6.5, color=c)
cbar = fig.colorbar(im, ax=ax, shrink=0.55, pad=0.02,
                     extend="both")
cbar.set_label("log₂(HR)   (HR < 0.35 saturates blue; HR > 2.83 saturates red)",
               fontsize=7)
cbar.ax.tick_params(labelsize=7)
ax.set_xlabel("Outcome", fontsize=9, labelpad=8)
# Add a footnote-style note about grey cells
ax.text(0.5, -0.18,
        "Grey cells = unreliable HR estimate (insufficient events for stable Cox fit; SCAU22–25 omitted).",
        transform=ax.transAxes, ha="center", va="top",
        fontsize=6.5, color="#555555", style="italic")
save(fig, "Figure5_heatmap_per_milestone_R1")

