def save(fig, name, dpi=290):
    """Save PDF + PNG + SVG. dpi=290 keeps tight-bbox PNGs ≤1800px longest side.
    Vector PDF/SVG are unconstrained.
    Strips any trailing _R1 from the filename — submitted figures must not carry revision markers."""
    name = name.replace("_R1", "")
    fig.savefig(os.path.join(FIG, f"{name}.pdf"), bbox_inches="tight")
    fig.savefig(os.path.join(FIG, f"{name}.png"), bbox_inches="tight", dpi=dpi)
    fig.savefig(os.path.join(FIG, f"{name}.svg"), bbox_inches="tight")
    plt.close(fig)
    print(f"  Saved {name}.{{pdf,png,svg}}")

