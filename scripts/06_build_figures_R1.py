#!/usr/bin/env python3
"""
06_build_figures_R1.py — submission-ready figures for R1 revision.

Specs (per CLAUDE.md):
  • PNG longest side ≤ 1800px (figsize × dpi ≤ 1800)
  • Vector PDF + SVG companion files
  • No plt.title() / ax.set_title()
  • No legends inside axes (only bbox_to_anchor outside or none)
  • tight_layout / constrained_layout on every figure
  • bbox_inches='tight' on every savefig
  • DPI ≥ 300 on every PNG
  • Professional colorblind-friendly palettes (seaborn muted/deep)
  • Text-background contrast verified (white on dark, black on light)
  • Diverse chart types — no two figures are the same kind

Figures produced:
  1. flowchart   — CONSORT-style cohort flow (Sankey-like swim lane)
  2. forest_A_B  — paired forest plot (Model A vs Model B) ordered by domain
  3. KM_tertiles — Kaplan-Meier by SCOPA-AUT tertile + risk table
  4. domain_lolli— Domain-level Cox HRs (lollipop chart)
  5. heatmap     — Per-milestone item × outcome HR heatmap with FDR stars
  6. lasso_path  — LASSO Cox coefficient path
  7. discrim_bar — Nested-model discrimination (C-index, AUC, IBS)
  8. calibration — Calibration plot at t=4y (already generated by script 05)
  9. milestone_donut — Proportional contribution of m10–m15 to composite events
"""
