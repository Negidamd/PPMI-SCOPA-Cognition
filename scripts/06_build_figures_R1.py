# Figure 2: Paired Forest plot (Model A vs Model B) ordered by domain
# ═══════════════════════════════════════════════════════════════════════
print("\nFigure 2 — Paired forest plot (Model A vs Model B)")
A = pd.read_csv(os.path.join(TAB, "cox_R1_item_modelA.csv"))
B = pd.read_csv(os.path.join(TAB, "cox_R1_item_modelB.csv"))
A["domain"] = A.Item.apply(item_domain)
B["domain"] = B.Item.apply(item_domain)
# Restrict to items 1–21 (full availability)
keep = [f"SCAU{i}" for i in range(1, 22)]
A = A[A.Item.isin(keep)].copy()
B = B[B.Item.isin(keep)].copy()
# Order by domain then SCAU number
A["scau_num"] = A.Item.str.replace("SCAU", "").astype(int)
B["scau_num"] = B.Item.str.replace("SCAU", "").astype(int)
order = ["GI", "Urinary", "Cardiovascular", "Thermoregulatory"]
A["dom_ord"] = A.domain.map({d: i for i, d in enumerate(order)})
B["dom_ord"] = B.domain.map({d: i for i, d in enumerate(order)})
A = A.sort_values(["dom_ord", "scau_num"]).reset_index(drop=True)
B = B.sort_values(["dom_ord", "scau_num"]).reset_index(drop=True)

XLIM_LO, XLIM_HI = 0.5, 3.5   # widen so CIs fit; "clip arrows" added for CIs beyond
fig, axes = plt.subplots(1, 2, figsize=(6.0, 5.5), sharey=True,
                          constrained_layout=True)
y_positions = np.arange(len(A))[::-1]
for ax, df, mlabel, hr_col, lo_col, hi_col, p_col in [
    (axes[0], A, "Model A (original covariates)",
     "HR", "CI_low", "CI_high", "p_fdr"),
    (axes[1], B, "Model B (expanded adjustment)",
     "HR", "CI_low", "CI_high", "p_fdr")]:
    for y_i, (_, row) in zip(y_positions, df.iterrows()):
        c = DOM_COLORS[row["domain"]]
        sig = (row[p_col] < 0.05) if pd.notna(row[p_col]) else False
        # Clip CI ends to plot range; if truncated, mark with a tiny triangle
        lo = max(row[lo_col], XLIM_LO)
        hi = min(row[hi_col], XLIM_HI)
        # Single thin CI line ─ no double-stroke
        ax.plot([lo, hi], [y_i, y_i],
                color=c, linewidth=1.4, solid_capstyle="butt", zorder=2)
        # Caps at CI ends
        for x_cap in (lo, hi):
            ax.plot([x_cap, x_cap], [y_i-0.18, y_i+0.18],
                    color=c, linewidth=1.0, zorder=2)
        # HR point: filled (FDR-sig) / hollow (NS)
        if sig:
            ax.scatter([row[hr_col]], [y_i], color=c, s=42,
                       edgecolor="black", linewidth=0.6, zorder=3)
        else:
            ax.scatter([row[hr_col]], [y_i], facecolor="white", s=28,
                       edgecolor=c, linewidth=1.0, zorder=3)
        # If CI truncated at the right limit, add a small arrow marker
        if row[hi_col] > XLIM_HI:
            ax.annotate("", xy=(XLIM_HI*1.03, y_i), xytext=(XLIM_HI*0.99, y_i),
                        arrowprops=dict(arrowstyle="->", color=c, lw=0.8))
    ax.axvline(1, color="grey", linestyle="--", linewidth=0.7, zorder=1)
    ax.set_xlabel("Adjusted hazard ratio (95% CI)")
    ax.set_xlim(XLIM_LO, XLIM_HI)
    ax.set_xscale("log")
    ax.set_xticks([0.5, 1, 1.5, 2, 3])
    ax.set_xticklabels(["0.5","1","1.5","2","3"])
    ax.minorticks_off()    # remove minor ticks that collide with majors
    ax.tick_params(axis="x", labelsize=8)
    ax.text(0.01, 1.005, mlabel, transform=ax.transAxes,
            ha="left", va="bottom", fontsize=9, weight="bold")
# Y labels colored by domain (left panel only)
axes[0].set_yticks(y_positions)
